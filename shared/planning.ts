import type { Workspace, Transaction } from './types'
import { previousWorkingDay } from './workdays'
import type { PlanVersion, ProjectedOccurrence, PlanDirection } from './planning-types'

const dayMs = 86400000
const utc = (date: string) => new Date(`${date}T00:00:00Z`)
export function addDays(date: string, days: number) {
  const value = utc(date)
  value.setUTCDate(value.getUTCDate() + days)
  return value.toISOString().slice(0, 10)
}
export function shiftMonth(month: string, delta: number) {
  const value = utc(`${month}-01`)
  value.setUTCMonth(value.getUTCMonth() + delta)
  return value.toISOString().slice(0, 7)
}
export function monthRange(month: string) {
  return { from: `${month}-01`, to: addDays(`${shiftMonth(month, 1)}-01`, -1) }
}
function clampedDate(year: number, month: number, day: number) {
  const start = utc(`${String(year).padStart(4, '0')}-${String(month).padStart(2, '0')}-01`)
  start.setUTCMonth(start.getUTCMonth() + 1)
  start.setUTCDate(0)
  return `${String(year).padStart(4, '0')}-${String(month).padStart(2, '0')}-${String(Math.min(day, start.getUTCDate())).padStart(2, '0')}`
}
/** Scheduled dates of one plan version inside [from, to], clipped by its start, end and validity. */
export function recurringDates(version: PlanVersion, from: string, to: string): string[] {
  const low = [from, version.startDate, version.validFrom].sort().at(-1)!
  const high = [to, version.endDate, version.validTo].filter((v): v is string => !!v).sort()[0]!
  if (low > high) return []
  if (version.frequency === 'custom')
    return (version.customDates || [])
      .map((r) => r.date)
      .filter((d) => d >= low && d <= high)
      .sort()
  if (version.frequency === 'once') return [version.startDate]
  const [year, month, day] = version.startDate.split('-').map(Number) as [number, number, number]
  const output: string[] = []
  if (version.frequency === 'weekly') {
    const step = version.interval * 7
    const count = Math.max(
      0,
      Math.ceil((utc(low).getTime() - utc(version.startDate).getTime()) / dayMs / step),
    )
    for (
      let date = addDays(version.startDate, count * step);
      date <= high;
      date = addDays(date, step)
    )
      output.push(date)
  } else if (version.frequency === 'monthly') {
    const [lowYear, lowMonth] = low.split('-').map(Number) as [number, number]
    const distance = (lowYear - year) * 12 + lowMonth - month
    let index = Math.max(0, Math.floor(distance / version.interval))
    // Several pay days a month (the 5th and the 20th) or the day of the first date.
    const days = version.monthDays?.length ? version.monthDays : [day]
    for (;;) {
      const nextMonth = shiftMonth(version.startDate.slice(0, 7), index * version.interval)
      if (`${nextMonth}-01` > high) break
      const [nextYear, nextNumber] = nextMonth.split('-').map(Number) as [number, number]
      const dates = new Set(days.map((d) => clampedDate(nextYear, nextNumber, d)))
      for (const date of [...dates].sort()) if (date >= low && date <= high) output.push(date)
      index++
    }
  } else {
    let index = Math.max(0, Math.floor((Number(low.slice(0, 4)) - year) / version.interval))
    for (
      let nextYear = year + index * version.interval;
      nextYear <= Number(high.slice(0, 4));
      nextYear += version.interval
    ) {
      const date = clampedDate(nextYear, month, day)
      if (date >= low && date <= high) output.push(date)
    }
  }
  return output
}
export type PlanningWorkspace = Pick<
  Workspace,
  'plans' | 'planVersions' | 'planOccurrences' | 'transactions' | 'deletedTransactions'
>
// The longest stretch of days off (New Year holidays) a pay day can move back over.
const shiftWindow = 16
type Selection = { from: string; to: string } | { planId: string; dueDate: string }
function project(workspace: PlanningWorkspace, selection: Selection): ProjectedOccurrence[] {
  const plans = new Map(workspace.plans.map((p) => [p.id, p]))
  const byDate = 'from' in selection
  // Scheduled dates are generated by their original date; a moved date is found through its
  // decision record, and the effective date is filtered at the end.
  const from = byDate ? selection.from : selection.dueDate
  const to = byDate ? selection.to : selection.dueDate
  // A date shortly after the range can move back into it when it falls on a day off.
  const scheduleTo = byDate ? addDays(to, shiftWindow) : to
  const result = new Map<string, ProjectedOccurrence>()
  const shifted = new Map<string, string>()
  for (const version of workspace.planVersions) {
    if (!byDate && version.planId !== selection.planId) continue
    const plan = plans.get(version.planId)
    if (!plan) continue
    for (const dueDate of recurringDates(version, from, scheduleTo)) {
      const key = `${version.planId}:${dueDate}`
      const date = version.holidayShift === 'before' ? previousWorkingDay(dueDate) : dueDate
      if (date !== dueDate) shifted.set(key, date)
      result.set(key, {
        id: key,
        planId: version.planId,
        dueDate,
        date,
        title: version.title,
        category: version.category,
        amount: version.customDates?.find((r) => r.date === dueDate)?.amount || version.amount,
        accountId: version.accountId,
        note: version.note,
        status: 'pending',
        transactionId: null,
        movedTo: null,
        direction: plan.direction,
        source: plan.source,
        creditAccountId: plan.source === 'credit' ? plan.sourceId : null,
        frequency: plan.frequency,
        actualAmount: null,
        actualDate: null,
      })
    }
  }
  const transactions = new Map(
    [...workspace.transactions, ...workspace.deletedTransactions].map((t) => [t.id, t]),
  )
  for (const occurrence of workspace.planOccurrences) {
    const plan = plans.get(occurrence.planId)
    if (!plan) continue
    const relevant = byDate
      ? (occurrence.dueDate >= from && occurrence.dueDate <= scheduleTo) ||
        (!!occurrence.movedTo && occurrence.movedTo >= from && occurrence.movedTo <= to)
      : occurrence.planId === selection.planId && occurrence.dueDate === selection.dueDate
    if (!relevant) continue
    const transaction = occurrence.transactionId
      ? transactions.get(occurrence.transactionId)
      : undefined
    const key = `${occurrence.planId}:${occurrence.dueDate}`
    result.set(key, {
      ...occurrence,
      id: key,
      date: occurrence.movedTo || shifted.get(key) || occurrence.dueDate,
      direction: plan.direction,
      source: plan.source,
      creditAccountId: plan.source === 'credit' ? plan.sourceId : null,
      frequency: plan.frequency,
      status:
        occurrence.status === 'paid' && (!transaction || transaction.deletedAt)
          ? 'deleted'
          : occurrence.status,
      actualAmount: transaction?.amount || null,
      actualDate: transaction?.date || null,
    })
  }
  return [...result.values()]
    .filter((item) => !byDate || (item.date >= from && item.date <= to))
    .sort((a, b) => a.date.localeCompare(b.date) || a.title.localeCompare(b.title, 'ru'))
}
/** Planned incomes and payments whose effective date falls inside [from, to]. */
export function projectPlans(workspace: PlanningWorkspace, from: string, to: string) {
  return project(workspace, { from, to })
}
/** One scheduled date of a plan by its original date, wherever it was moved to. */
export function projectOccurrence(
  workspace: PlanningWorkspace,
  planId: string,
  dueDate: string,
): ProjectedOccurrence | undefined {
  return project(workspace, { planId, dueDate })[0]
}
/** Still waiting for a decision: not confirmed, cancelled or closed. */
export function isOpen(item: Pick<ProjectedOccurrence, 'status'>) {
  return item.status === 'pending' || item.status === 'deleted'
}
/** Open plans whose date has passed: they need to be confirmed, moved or cancelled. */
export function overduePlans(workspace: PlanningWorkspace, today: string, days = 90) {
  return projectPlans(workspace, addDays(today, -days), addDays(today, -1)).filter(isOpen)
}
export function categorySpending(transactions: Transaction[], month: string) {
  const totals = new Map<string, bigint>()
  for (const t of transactions)
    if (!t.deletedAt && t.kind === 'expense' && t.date.startsWith(month + '-'))
      totals.set(t.category, (totals.get(t.category) || 0n) + BigInt(t.amount))
  return totals
}
function openTotal(items: ProjectedOccurrence[], direction: PlanDirection) {
  return items
    .filter((item) => item.source !== 'credit' && item.direction === direction && isOpen(item))
    .reduce((sum, item) => sum + BigInt(item.amount), 0n)
}
/** Income and payment plan of a month: what already happened and what is still expected. */
export function monthPlan(workspace: PlanningWorkspace, month: string) {
  const range = monthRange(month)
  const items = projectPlans(workspace, range.from, range.to)
  const actual = (kind: 'income' | 'expense') =>
    workspace.transactions
      .filter((t) => !t.deletedAt && t.kind === kind && t.date.startsWith(month + '-'))
      .reduce((sum, t) => sum + BigInt(t.amount), 0n)
  const received = actual('income'),
    expectedIncome = openTotal(items, 'income'),
    spent = actual('expense'),
    expectedPayments = openTotal(items, 'expense')
  return {
    received: received.toString(),
    expectedIncome: expectedIncome.toString(),
    incomeTotal: (received + expectedIncome).toString(),
    spent: spent.toString(),
    expectedPayments: expectedPayments.toString(),
    balance: (received + expectedIncome - spent - expectedPayments).toString(),
  }
}
export function budgetRows(workspace: Workspace, month: string) {
  const spent = categorySpending(workspace.transactions, month),
    planned = new Map<string, bigint>()
  const range = monthRange(month)
  for (const item of projectPlans(workspace, range.from, range.to))
    if (item.source !== 'credit' && item.direction === 'expense' && isOpen(item))
      planned.set(item.category, (planned.get(item.category) || 0n) + BigInt(item.amount))
  return workspace.budgets
    .filter((b) => b.month === month)
    .map((b) => {
      const actual = spent.get(b.category) || 0n,
        future = planned.get(b.category) || 0n,
        limit = BigInt(b.limit)
      return {
        ...b,
        spent: actual.toString(),
        planned: future.toString(),
        remaining: (limit - actual).toString(),
        afterPlanned: (limit - actual - future).toString(),
        percent:
          limit === 0n ? (actual > 0n ? 100 : 0) : Math.min(100, Number((actual * 100n) / limit)),
      }
    })
    .sort((a, b) => a.category.localeCompare(b.category, 'ru'))
}
export function frequencyLabel(frequency: string, interval: number, monthDays: number[] = []) {
  if (frequency === 'custom') return 'По введённым датам'
  if (frequency === 'once') return 'Один раз'
  if (frequency === 'monthly' && monthDays.length > 1) {
    const days = monthDays.slice(0, -1).join(', ') + ' и ' + monthDays.at(-1)
    return `${interval === 1 ? 'Каждый месяц' : `Каждые ${interval} мес.`}, ${days} числа`
  }
  if (frequency === 'weekly') return interval === 1 ? 'Каждую неделю' : `Каждые ${interval} нед.`
  if (frequency === 'yearly') return interval === 1 ? 'Каждый год' : `Каждые ${interval} лет`
  return interval === 1 ? 'Каждый месяц' : `Каждые ${interval} мес.`
}
